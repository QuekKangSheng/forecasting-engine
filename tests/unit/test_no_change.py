@pytest.fixture(scope="module")
def carry_runs():
    """The derived polynomial on the carry world, without and with its level panel."""
    frame = _carry_world()
    page = _page_panel(frame)
    without = derive_polynomial(page, _splitter())
    with_levels = derive_polynomial(page, _splitter(), level_panel=_levels(frame))
    return page, without, with_levels


def test_without_a_level_panel_the_derived_polynomial_is_exactly_mains(carry_runs):
    golden = pd.read_csv(GOLDEN, index_col="date", parse_dates=True)
    _page, without, _with = carry_runs

    assert without.result.forecast.index.equals(golden.index)
    np.testing.assert_allclose(without.result.forecast, golden["forecast"], rtol=1e-12, atol=0)
    np.testing.assert_allclose(without.result.baseline, golden["baseline"], rtol=1e-12, atol=0)
    np.testing.assert_allclose(without.result.realised, golden["realised"], rtol=1e-12, atol=0)
    assert set(without.scores) == {"degree1_lasso", "degree2_lasso", "degree3_lasso", SHRINKAGE}


def test_a_level_panel_adds_both_no_change_candidates_and_leaves_the_others_scores_alone(
    carry_runs,
):
    _page, without, with_levels = carry_runs

    assert set(with_levels.scores) == set(without.scores) | {NO_CHANGE, NO_CHANGE_EXPANDING}
    for name, score in without.scores.items():
        assert with_levels.scores[name] == score


def test_a_no_change_winner_says_it_reads_levels_and_which_window_it_trained_on(carry_runs):
    page, _without, run = carry_runs

    assert run.winner in (NO_CHANGE, NO_CHANGE_EXPANDING)
    assert run.scores[run.winner] == max(run.scores.values())
    assert run.reads_levels
    assert run.panel is not page
    assert run.panel.signals == ("gauge", "rate")
    assert set(run.description.terms) <= set(run.panel.signals)
    assert run.expanding == (run.winner == NO_CHANGE_EXPANDING)
    assert run.expanding == (run.splitter.train is None)
    assert (run.splitter.test, run.splitter.embargo) == (_splitter().test, _splitter().embargo)


def test_a_winner_on_the_page_panel_says_so(carry_runs):
    page, without, _with = carry_runs

    assert without.winner not in (NO_CHANGE, NO_CHANGE_EXPANDING)
    assert without.panel is page
    assert not without.reads_levels
    assert not without.expanding


def test_run_derived_polynomial_reports_the_same_winner():
    frame = _carry_world()
    page, levels = _page_panel(frame), _levels(frame)

    result, description = run_derived_polynomial(page, _splitter(), level_panel=levels)
    run = derive_polynomial(page, _splitter(), level_panel=levels)

    pd.testing.assert_series_equal(result.forecast, run.result.forecast)
    assert description == run.description



def _short_splitter() -> PurgedWalkForward:
    """Training windows of 25 rows, enough for a lasso but short of the no-change fit's
    30, on the rolling window and, from its first fold, the expanding one too."""
    return PurgedWalkForward(train=25, test=20, embargo=5, tuning_rows=0)


def test_a_no_change_fit_the_data_leaves_too_few_rows_for_is_left_out_with_why():
    frame = _carry_world()
    page, lasso = _page_panel(frame), (DerivedPolynomial(degree=1),)

    without = derive_polynomial(page, _short_splitter(), lasso, shrinkage=False)
    run = derive_polynomial(
        page, _short_splitter(), lasso, shrinkage=False, level_panel=_levels(frame)
    )

    assert set(run.left_out) == {NO_CHANGE, NO_CHANGE_EXPANDING}
    assert all("not enough complete training rows" in why for why in run.left_out.values())
    assert run.scores == without.scores
    assert run.winner == without.winner == "degree1_lasso"
    pd.testing.assert_series_equal(run.result.forecast, without.result.forecast)
    assert without.left_out == {}


def test_with_nothing_but_a_no_change_fit_that_cannot_be_fitted_the_run_says_why():
    frame = _carry_world()

    with pytest.raises(PolynomialConfigError, match="not enough complete training rows"):
        derive_polynomial(
            _page_panel(frame), _short_splitter(), (), shrinkage=False, level_panel=_levels(frame)
        )


# --- the no-change fits alone (no_change_only) ----------------------------------------


def test_with_no_change_only_just_the_two_no_change_fits_run_and_one_wins():
    frame = _carry_world()

    run = derive_polynomial(
        _page_panel(frame), _splitter(), level_panel=_levels(frame), no_change_only=True
    )

    assert set(run.scores) == {NO_CHANGE, NO_CHANGE_EXPANDING}
    assert run.winner in (NO_CHANGE, NO_CHANGE_EXPANDING)
    assert run.reads_levels
    assert run.fallback is None
    assert run.left_out == {}


def test_with_no_change_only_the_scores_are_those_the_full_grid_gives_the_same_fits(carry_runs):
    page, _without, with_levels = carry_runs
    frame = _carry_world()

    only = derive_polynomial(page, _splitter(), level_panel=_levels(frame), no_change_only=True)

    for name in (NO_CHANGE, NO_CHANGE_EXPANDING):
        assert only.scores[name] == with_levels.scores[name]


def test_with_no_change_only_and_no_level_panel_the_ordinary_grid_runs_and_says_why(carry_runs):
    page, without, _with = carry_runs

    run = derive_polynomial(page, _splitter(), no_change_only=True)

    pd.testing.assert_series_equal(run.result.forecast, without.result.forecast)
    assert run.scores == without.scores
    assert run.winner == without.winner
    assert run.fallback is not None
    assert "no rate, spread or gauge" in run.fallback


def test_with_no_change_only_and_no_state_series_the_ordinary_grid_runs_and_says_why(carry_runs):
    page, without, _with = carry_runs
    empty = level_panel(_carry_world(), ["gauge"], {"gauge": Transform.LOG_RETURN}, "price", H)

    run = derive_polynomial(page, _splitter(), level_panel=empty, no_change_only=True)

    assert empty is None
    assert run.scores == without.scores
    assert run.fallback is not None


def test_with_no_change_only_and_neither_fit_possible_the_ordinary_grid_runs_and_says_why():
    frame = _carry_world()
    page, lasso = _page_panel(frame), (DerivedPolynomial(degree=1),)

    run = derive_polynomial(
        page,
        _short_splitter(),
        lasso,
        shrinkage=False,
        level_panel=_levels(frame),
        no_change_only=True,
    )
    ordinary = derive_polynomial(page, _short_splitter(), lasso, shrinkage=False)

    assert set(run.scores) == {"degree1_lasso"}
    assert run.winner == "degree1_lasso"
    pd.testing.assert_series_equal(run.result.forecast, ordinary.result.forecast)
    assert run.fallback is not None
    assert "neither could be fitted" in run.fallback
    assert "not enough complete training rows" in run.fallback
    assert run.left_out == {}


def test_without_no_change_only_the_run_is_as_before_and_has_no_fallback(carry_runs):
    _page, without, with_levels = carry_runs

    assert without.fallback is None
