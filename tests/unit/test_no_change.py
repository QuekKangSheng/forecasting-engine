def test_the_inputs_are_the_signals_read_as_levels_or_differences_never_prices():
    transforms = {
        "dxy": Transform.LOG_RETURN,
        "vix": Transform.LEVEL,
        "yield": Transform.DIFFERENCE,
    }

    assert state_columns(["dxy", "vix", "yield"], transforms) == ("vix", "yield")


def test_the_level_panel_reads_each_state_series_as_its_level_lagged_one_row():
    frame = _carry_world()

    panel = _levels(frame)

    assert panel.signals == ("gauge", "rate")
    assert {a.transform for a in panel.alignment.values()} == {Transform.LEVEL}
    pd.testing.assert_series_equal(panel.frame["rate"], frame["rate"].shift(1), check_freq=False)
    pd.testing.assert_series_equal(
        panel.frame[panel.targets[0]], _page_panel(frame).frame[panel.targets[0]]
    )


def test_with_no_state_series_there_is_no_level_panel():
    frame = _carry_world().rename(columns={"rate": "dxy"})

    assert level_panel(frame, ["dxy"], {"dxy": Transform.LOG_RETURN}, "price", H) is None


# --- what the fit recovers -----------------------------------------------------------

#: The carry world of the November 2026 research: a yield in percent that is a random
#: walk, earning 1/252 of itself a day and losing 6 (duration) per point it rises.
CARRY_PER_DAY = 1 / 252 / 100
DURATION = 6.0


def _yield_world(seed: int = 0, n: int = 1500) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    idx = pd.bdate_range("2010-01-04", periods=n)
    yld = 2.5 + np.cumsum(rng.normal(scale=0.055, size=n))
    gauge = np.empty(n)
    gauge[0] = 0.0
    for t in range(1, n):
        gauge[t] = 0.97 * gauge[t - 1] + rng.normal()
    daily = np.r_[
        0.0,
        CARRY_PER_DAY * yld[:-1]
        - DURATION * np.diff(yld) / 100
        - 0.0003 * np.diff(gauge)
        + rng.normal(scale=0.0001, size=n - 1),
    ]
    price = 100 * np.exp(np.cumsum(daily))
    return pd.DataFrame({"yield": yld, "gauge": gauge, "price": price}, index=idx)


def test_the_fit_recovers_the_carry_where_a_plain_regression_on_the_level_is_badly_biased():
    horizon = 20
    frame = _yield_world()
    transforms = {"yield": Transform.DIFFERENCE, "gauge": Transform.LEVEL}
    panel = level_panel(frame, ["gauge", "yield"], transforms, "price", horizon)
    train = panel.frame.index[1 : len(panel.frame) - horizon - 1]
    truth = CARRY_PER_DAY * horizon  # h-day return per point of yield

    description = _fitted(panel, train).describe()
    slope = dict(zip(description.terms, description.coefficients, strict=True))["yield"]
    per_point = slope / description.standardisation["yield"][1]
    rows = panel.frame.loc[train, ["yield", panel.targets[0]]].dropna()
    plain = np.polyfit(rows["yield"], rows[panel.targets[0]], 1)[0]

    assert per_point == pytest.approx(truth, rel=0.3)
    assert plain > 3 * truth


def test_the_description_reproduces_the_forecast_in_the_scenario_engine_even_when_clipped():
    panel = _levels(_carry_world())
    train = panel.frame.index[1:400]
    model = _fitted(panel, train)
    description = model.describe()
    assert description.terms  # the fit kept something to reproduce
    function = ActiveFunction(
        Origin.DERIVED,
        description,
        dict.fromkeys(function_inputs(description, Origin.DERIVED, panel.signals), Transform.LEVEL),
    )
    rows = panel.frame.iloc[400:460].copy()
    # Push some inputs far past their training range, so the clip bounds apply.
    rows.iloc[:5, rows.columns.get_loc("rate")] = 50.0
    rows.iloc[5:10, rows.columns.get_loc("gauge")] = -100.0
    shocked = replace(panel, frame=rows)

    predicted = model.predict(shocked, rows.index)
    by_function = [evaluate_function(function, row.to_dict()) for _, row in rows.iterrows()]

    np.testing.assert_allclose(by_function, predicted.to_numpy(), rtol=1e-12, atol=1e-15)
    low, high = description.input_bounds["rate"]
    assert 50.0 > high  # the first rows really were clipped


def test_a_row_missing_an_input_gets_no_forecast():
    panel = _levels(_carry_world())
    model = _fitted(panel, panel.frame.index[1:400])
    holed = panel.frame.copy()
    holed.iloc[450, holed.columns.get_loc("gauge")] = np.nan
    holed_panel = replace(panel, frame=holed)

    forecast = model.predict(holed_panel, holed.index[440:460])

    assert np.isnan(forecast.iloc[10])
    assert forecast.drop(holed.index[450]).notna().all()


def test_too_few_complete_training_rows_is_refused_with_a_clear_message():
    panel = _levels(_carry_world())

    with pytest.raises(NoChangeDataError, match="not enough complete training rows"):
        _fitted(panel, panel.frame.index[1:20])


