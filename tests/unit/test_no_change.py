H = 5
#: How the page's transform map reads the two inputs: the rate as a 1-row difference,
#: the gauge as a level.
PAGE_TRANSFORMS = {"rate": Transform.DIFFERENCE, "gauge": Transform.LEVEL}

#: Pooled forecasts, baselines and realised returns from origin/main's
#: ``run_derived_polynomial`` (475c42b) on ``_carry_world()``'s page panel at h = 5 with
#: ``_splitter()``. Generated by running this module's fixture against main's ``src``.
GOLDEN = Path(__file__).parent / "golden" / "derived_main_golden.csv"


def _carry_world(n: int = 700, seed: int = 11) -> pd.DataFrame:
    """A rate whose level earns a return and whose moves cost one, a persistent gauge,
    and a price, on business days."""
    rng = np.random.default_rng(seed)
    idx = pd.bdate_range("2016-01-04", periods=n)
    rate = 2.5 + np.cumsum(rng.normal(scale=0.05, size=n))
    gauge = np.empty(n)
    gauge[0] = 18.0
    for t in range(1, n):
        gauge[t] = 18.0 + 0.97 * (gauge[t - 1] - 18.0) + rng.normal()
    daily = np.r_[
        0.0,
        0.002 * (rate[:-1] - 2.5) - 0.06 * np.diff(rate) + rng.normal(scale=0.001, size=n - 1),
    ]
    price = 100 * np.exp(np.cumsum(daily))
    return pd.DataFrame({"rate": rate, "gauge": gauge, "price": price}, index=idx)


def _splitter() -> PurgedWalkForward:
    return PurgedWalkForward(train=120, test=20, embargo=5, tuning_rows=200)


def _levels(frame: pd.DataFrame, horizon: int = H):
    return level_panel(frame, ["gauge", "rate"], PAGE_TRANSFORMS, "price", horizon)


def _page_panel(frame: pd.DataFrame):
    return align_and_lag(frame, ["gauge", "rate"], "price", horizon=H, transforms=PAGE_TRANSFORMS)


def _fitted(panel, train) -> NoChangePolynomial:
    model = NoChangePolynomial()
    model.fit(panel, train)
    return model


