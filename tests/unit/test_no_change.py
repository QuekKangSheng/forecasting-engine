def test_a_rows_news_is_each_inputs_change_over_that_rows_own_label_window():
    frame = _carry_world()
    panel = _levels(frame)

    news = label_window_news(panel)

    expected = frame["rate"].shift(-H) - frame["rate"]
    pd.testing.assert_series_equal(
        news["rate"].iloc[: -H - 1], expected.iloc[: -H - 1], check_freq=False, check_names=False
    )
    # The last rows' windows end past the data the panel holds, so they have no news.
    assert news.iloc[-H - 1 :].isna().all().all()


def _fold(panel, number: int):
    return list(_splitter().split(panel))[number]


def test_no_value_dated_on_or_after_the_test_window_changes_the_fit():
    frame = _carry_world()
    train, test = _fold(_levels(frame), 10)
    later = frame.index >= test[0]
    rng = np.random.default_rng(0)
    rewritten = frame.copy()
    rewritten.loc[later] *= rng.uniform(0.5, 1.5, size=(int(later.sum()), frame.shape[1]))

    before = _fitted(_levels(frame), train).describe()
    after = _fitted(_levels(rewritten), train).describe()

    assert after == before


def test_the_last_value_the_training_labels_reach_does_change_the_fit():
    # The check above would pass vacuously if the fit read nothing near its window's
    # end: the day before the test window is in the last training label's window.
    frame = _carry_world()
    train, test = _fold(_levels(frame), 10)
    rewritten = frame.copy()
    day_before = frame.index[frame.index.get_loc(test[0]) - 1]
    rewritten.loc[day_before, "rate"] += 0.5

    before = _fitted(_levels(frame), train).describe()
    after = _fitted(_levels(rewritten), train).describe()

    assert after != before


def test_a_row_whose_label_or_news_is_not_yet_complete_is_not_used():
    panel = _levels(_carry_world())
    index = panel.frame.index
    # A label needs the price h rows on and a row's news the level h + 1 rows on,
    # which the panel does not yet hold for its last h + 1 rows.
    complete = index[: len(index) - H - 1]
    assert panel.frame[panel.targets[0]].iloc[-H - 1 :].notna().iloc[0]

    everything = _fitted(panel, index).describe()
    only_complete = _fitted(panel, complete).describe()

    assert everything == only_complete


# --- a fold that keeps nothing, and its level -------------------------------------------


def _noise_world(n: int = 700, seed: int = 3) -> pd.DataFrame:
    """Rates and a gauge that move the price but whose levels earn nothing."""
    rng = np.random.default_rng(seed)
    idx = pd.bdate_range("2016-01-04", periods=n)
    rate = 2.5 + np.cumsum(rng.normal(scale=0.05, size=n))
    gauge = 18 + np.cumsum(rng.normal(size=n))
    daily = np.r_[0.0, -0.06 * np.diff(rate) + rng.normal(scale=0.003, size=n - 1)]
    price = 100 * np.exp(np.cumsum(daily))
    return pd.DataFrame({"rate": rate, "gauge": gauge, "price": price}, index=idx)


def test_a_fold_that_keeps_no_term_forecasts_its_intercept_and_adds_exactly_no_signal():
    panel = _levels(_noise_world())
    folds = evaluate(NoChangePolynomial, panel, _splitter())
    empty = [f for f in folds if not f.description.terms]
    assert empty  # the noise world gives the lasso nothing to keep somewhere

    for fold in empty:
        intercept = fold.description.intercept
        assert (fold.predicted.dropna() == intercept).all()
        assert fold.own_level == intercept
        assert (signal_forecasts((fold,)).dropna() == 0.0).all()


def test_its_forecasts_are_judged_against_its_own_mean_in_sample_forecast():
    panel = _levels(_carry_world())
    folds = evaluate(NoChangePolynomial, panel, _splitter())
    varying = next(f for f in folds if f.description.terms)

    assert varying.own_level == pytest.approx(varying.predicted_train.mean(), rel=1e-12)
    assert varying.own_level != pytest.approx(varying.realised_train.mean(), rel=1e-6)
    pd.testing.assert_series_equal(
        signal_forecasts((varying,)), varying.predicted - varying.own_level
    )


